-- MASTER PRO AI: tabelas de aprendizado.
-- Este script NÃO altera nem apaga historico_analise.
-- É seguro rodar mais de uma vez (usa "if not exists" / "drop policy if exists").
-- Execute no SQL Editor do projeto Supabase existente.

-- ---------------------------------------------------------------
-- 1) Hipótese numérica (já existia)
-- ---------------------------------------------------------------
create table if not exists public.aprendizado_modelo (
  id bigint generated by default as identity primary key,
  session_id text not null,
  criado_em timestamptz not null default now(),
  base_ultimo_numero smallint,
  previsto_numero smallint not null check (previsto_numero between 0 and 36),
  previsto_cor text not null,
  previsto_faixa text not null,
  previsto_paridade text not null,
  resultado_real smallint check (resultado_real between 0 and 36),
  acertou_numero boolean,
  acertou_cor boolean,
  acertou_faixa boolean,
  acertou_paridade boolean,
  avaliado_em timestamptz
);

create index if not exists aprendizado_modelo_session_criado_idx
  on public.aprendizado_modelo (session_id, criado_em desc);

-- ---------------------------------------------------------------
-- 2) Avaliação das estratégias (FALTAVA no projeto original;
--    o app.js já usava esta tabela)
-- ---------------------------------------------------------------
create table if not exists public.aprendizado_estrategias (
  id bigint generated by default as identity primary key,
  session_id text not null,
  criado_em timestamptz not null default now(),
  janela smallint not null default 30,
  categoria text not null,
  estrategia text not null,
  sugestao text not null,
  peso numeric not null default 1,
  resultado_real smallint check (resultado_real between 0 and 36),
  acertou boolean,
  avaliado_em timestamptz
);

create index if not exists aprendizado_estrategias_session_criado_idx
  on public.aprendizado_estrategias (session_id, criado_em desc);

create index if not exists aprendizado_estrategias_pendentes_idx
  on public.aprendizado_estrategias (session_id)
  where resultado_real is null;

-- ---------------------------------------------------------------
-- 3) Segurança (RLS)
-- ---------------------------------------------------------------
alter table public.aprendizado_modelo enable row level security;
alter table public.aprendizado_estrategias enable row level security;

-- Sem login, o navegador usa a chave anon. Por isso estas policies são
-- simples, mas já mais restritas que antes:
--   * não existe DELETE;
--   * só dá para atualizar linhas AINDA NÃO avaliadas
--     (uma avaliação gravada não pode ser reescrita).
-- Para uso público de verdade, adicione autenticação e filtre por usuário.

drop policy if exists "masterpro_select_anon" on public.aprendizado_modelo;
create policy "masterpro_select_anon" on public.aprendizado_modelo
  for select to anon using (true);

drop policy if exists "masterpro_insert_anon" on public.aprendizado_modelo;
create policy "masterpro_insert_anon" on public.aprendizado_modelo
  for insert to anon with check (resultado_real is null);

drop policy if exists "masterpro_update_anon" on public.aprendizado_modelo;
create policy "masterpro_update_anon" on public.aprendizado_modelo
  for update to anon using (resultado_real is null) with check (true);

drop policy if exists "masterpro_select_anon" on public.aprendizado_estrategias;
create policy "masterpro_select_anon" on public.aprendizado_estrategias
  for select to anon using (true);

drop policy if exists "masterpro_insert_anon" on public.aprendizado_estrategias;
create policy "masterpro_insert_anon" on public.aprendizado_estrategias
  for insert to anon with check (resultado_real is null);

drop policy if exists "masterpro_update_anon" on public.aprendizado_estrategias;
create policy "masterpro_update_anon" on public.aprendizado_estrategias
  for update to anon using (resultado_real is null) with check (true);

grant select, insert, update on public.aprendizado_modelo to anon;
grant select, insert, update on public.aprendizado_estrategias to anon;
grant usage, select on sequence public.aprendizado_modelo_id_seq to anon;
grant usage, select on sequence public.aprendizado_estrategias_id_seq to anon;
